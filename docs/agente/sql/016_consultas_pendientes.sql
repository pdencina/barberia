-- Consultas difíciles: cuando el agente no sabe responder, se las pasa al dueño (número administrador) por WhatsApp.
-- El dueño responde con una instrucción; el agente redacta la respuesta al cliente y la guarda como pregunta propia (agent_faq_custom).
-- Aditiva y re-ejecutable. Solo guarda lo mínimo para poder responder (teléfono del cliente y su pregunta) y BORRA la fila al cerrarla.
CREATE TABLE IF NOT EXISTS public.agent_consultas (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  numero bigint GENERATED BY DEFAULT AS IDENTITY,
  tenant_id uuid NOT NULL REFERENCES public.tenants(id) ON DELETE CASCADE,
  contact_hash text NOT NULL,
  telefono text NOT NULL CHECK (telefono ~ '^[0-9]{8,15}$'),
  pregunta text NOT NULL CHECK (char_length(pregunta) BETWEEN 1 AND 500),
  notas text CHECK (notas IS NULL OR char_length(notas) <= 700),
  estado text NOT NULL DEFAULT 'abierta' CHECK (estado IN ('abierta')),
  aviso_wamid text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS agent_consultas_tenant_idx ON public.agent_consultas (tenant_id, created_at DESC);
CREATE INDEX IF NOT EXISTS agent_consultas_contacto_idx ON public.agent_consultas (tenant_id, contact_hash);
CREATE INDEX IF NOT EXISTS agent_consultas_wamid_idx ON public.agent_consultas (aviso_wamid) WHERE aviso_wamid IS NOT NULL;
ALTER TABLE public.agent_consultas ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.agent_consultas FROM PUBLIC, anon, authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.agent_consultas TO service_role;

